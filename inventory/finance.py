"""The finance view: stock is cash. How much working capital each service level ties up, and what it buys.

A store manager asks "how often will we run out?". Finance asks "how much cash is sitting on the
shelves, and what do we get for it?". This module answers finance from the same backtest, comparing
every service level with the client's current one.

    python -m inventory.finance     # writes data/processed/working_capital.csv and docs/finance-summary.md

Working capital here is the average value of stock on hand at unit cost over the 2011 backtest.
The holding rate already includes the cost of the capital tied up, so it is not counted twice.
"""
import sys
from pathlib import Path

import pandas as pd

from .settings import SettingsError, load as load_settings

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
SUMMARY_MD = ROOT / "docs" / "finance-summary.md"
SYMBOLS = {"GBP": "£", "USD": "$", "EUR": "€"}


def working_capital(tradeoff, baseline):
    """One row per service level, with the change against the baseline (current) level."""
    t = tradeoff.set_index("service_level").sort_index()
    if baseline not in t.index:
        raise ValueError(f"Baseline service level {baseline} is not in the backtest results")
    base = t.loc[baseline]
    out = pd.DataFrame({
        "service_level": t.index,
        "fill_rate": t["fill_rate"].values,
        "working_capital": t["avg_stock_value"].round(2).values,
        "holding_cost": t["holding_cost"].values,
        "lost_margin": t["lost_margin"].values,
        "total_cost": t["total_cost"].values,
    })
    out["extra_working_capital"] = (out["working_capital"] - base["avg_stock_value"]).round(2)
    out["extra_holding_cost"] = (out["holding_cost"] - base["holding_cost"]).round(2)
    out["lost_margin_recovered"] = (base["lost_margin"] - out["lost_margin"]).round(2)
    out["net_saving"] = (base["total_cost"] - out["total_cost"]).round(2)
    # Yearly net saving per unit of extra cash invested in stock. Undefined at the baseline itself, and
    # only meaningful when more cash is tied up (a lower level frees cash; its "return" is a cost avoided).
    extra = out["extra_working_capital"]
    out["return_on_extra_capital"] = (out["net_saving"] / extra).where(extra > 0).round(4)
    out["is_baseline"] = out["service_level"] == baseline
    return out


def steps(wc):
    """Each step up from one service level to the next: extra cash tied up, yearly net saving, return on it."""
    w = wc.sort_values("service_level").reset_index(drop=True)
    rows = []
    for lo, hi in zip(w.iloc[:-1].itertuples(), w.iloc[1:].itertuples()):
        extra = hi.working_capital - lo.working_capital
        saving = lo.total_cost - hi.total_cost
        rows.append({"from": lo.service_level, "to": hi.service_level, "extra_cash": round(extra, 2),
                     "net_saving": round(saving, 2), "return": round(saving / extra, 4) if extra > 0 else None})
    return rows


def recommend(wc, hurdle):
    """Step up from the lowest level while each step's extra stock earns at least the hurdle return a year.

    Lowest total cost alone would always pick the highest level here, even when the last step ties up
    thousands of pounds to save a few. Finance judges each step like any other use of cash.
    """
    level = float(wc["service_level"].min())
    for s in steps(wc):
        if s["return"] is None or s["return"] < hurdle:
            break
        level = float(s["to"])
    return level


def money(x, sym):
    sign = "-" if x < 0 else ""
    return f"{sign}{sym}{abs(x):,.0f}"


def summary_markdown(wc, settings):
    sym = SYMBOLS.get(settings.currency, settings.currency + " ")
    base = wc[wc["is_baseline"]].iloc[0]
    best_level = recommend(wc, settings.min_return_on_extra_stock)
    stepped = steps(wc)
    best = wc[wc["service_level"] == best_level].iloc[0]
    lines = ["# Finance summary: working capital by service level", "",
             "*Generated by `python -m inventory.finance` from the 2011 backtest. Do not edit by hand.*", "",
             f"Client: {settings.client}. Current service level: **{settings.default_service_level:.0%}**.", "",
             "## What the money says", ""]
    if best_level == settings.default_service_level:
        lines += [f"The current {best_level:.0%} level already has the lowest total yearly cost. No change is needed."]
    else:
        direction = "more" if best["extra_working_capital"] > 0 else "less"
        lines += [f"Moving from {settings.default_service_level:.0%} to **{best_level:.0%}** ties up "
                  f"{money(abs(best['extra_working_capital']), sym)} {direction} cash in stock on average. "
                  f"It adds {money(best['extra_holding_cost'], sym)} a year in holding cost, recovers "
                  f"{money(best['lost_margin_recovered'], sym)} of lost margin, and saves "
                  f"**{money(best['net_saving'], sym)} a year** overall."]
        if pd.notna(best["return_on_extra_capital"]):
            lines += ["", f"Each {sym}1 of extra stock returns about {best['return_on_extra_capital']:.0%} a year "
                          "after its holding cost."]
    nxt = next((s for s in stepped if s["from"] == best_level), None)
    if nxt:
        r = f"{nxt['return']:.1%}" if nxt["return"] is not None else "no return"
        lines += ["", f"The next step, to {nxt['to']:.0%}, would tie up {money(nxt['extra_cash'], sym)} more for "
                      f"{money(nxt['net_saving'], sym)} a year: {r} on the extra cash, below finance's "
                      f"{settings.min_return_on_extra_stock:.0%} hurdle. That is where extra stock stops paying for itself."]
    lines += ["", "## Each step up, judged as an investment", "",
              f"Finance's hurdle: extra stock must save at least {settings.min_return_on_extra_stock:.0%} of the "
              "extra cash a year, after its holding cost.", "",
              "| Step | Extra cash in stock | Net saving / yr | Return on extra cash | Clears hurdle |",
              "| --- | ---: | ---: | ---: | --- |"]
    lines += [f"| {s['from']:.0%} → {s['to']:.0%} | {money(s['extra_cash'], sym)} | {money(s['net_saving'], sym)} | "
              f"{'n/a' if s['return'] is None else format(s['return'], '.1%')} | "
              f"{'yes' if s['return'] is not None and s['return'] >= settings.min_return_on_extra_stock else 'no'} |"
              for s in stepped]
    lines += ["", "## By service level", "",
              "| Service level | Fill rate | Cash tied up in stock | Change vs current | Holding cost / yr | "
              "Lost margin / yr | Total cost / yr | Net saving vs current |",
              "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for r in wc.itertuples():
        label = f"{r.service_level:.0%}" + (" (current)" if r.is_baseline else "") + \
                (" **recommended**" if r.service_level == best_level and not r.is_baseline else "")
        lines.append(f"| {label} | {r.fill_rate:.1%} | {money(r.working_capital, sym)} | "
                     f"{'-' if r.is_baseline else money(r.extra_working_capital, sym)} | {money(r.holding_cost, sym)} | "
                     f"{money(r.lost_margin, sym)} | {money(r.total_cost, sym)} | "
                     f"{'-' if r.is_baseline else money(r.net_saving, sym)} |")
    lines += ["", "## Assumptions finance is asked to sign off", "",
              "| Assumption | Value | Source |", "| --- | --- | --- |",
              f"| Unit cost | {settings.unit_cost_share:.0%} of median selling price | config/client_settings.json |",
              f"| Holding cost, including cost of capital | {settings.holding_rate_year:.0%} of stock value per year | "
              "config/client_settings.json |",
              f"| Trading days per year | {settings.trading_days_year} | config/client_settings.json |",
              f"| Minimum return on extra stock | {settings.min_return_on_extra_stock:.0%} a year | "
              "config/client_settings.json |",
              f"| Supplier lead times | {settings.lead_time_range[0]}-{settings.lead_time_range[1]} trading days, "
              f"{len(settings.lead_time_overrides)} set by the client | config/client_settings.json |",
              "| Lost sale | Unmet demand is lost, valued at selling price minus unit cost | Model |",
              "| Demand | Real 2011 daily sales; policies set from 2010 only | UCI Online Retail II |", "",
              "Working capital is the average value of stock on hand at unit cost. The holding rate already "
              "includes the cost of tying up that cash, so it is not counted twice.", "",
              "| Signed off by | Name | Date |", "| --- | --- | --- |",
              f"| Store manager | {settings.sign_off.get('store_manager') or '______________'} | "
              f"{settings.sign_off.get('date') or '________'} |",
              f"| Finance | {settings.sign_off.get('finance') or '______________'} | "
              f"{settings.sign_off.get('date') or '________'} |", ""]
    return "\n".join(lines)


def main(argv=None):
    products = pd.read_csv(PROCESSED / "products.csv", dtype={"product_code": str})
    try:
        settings = load_settings(ROOT / "config" / "client_settings.json", set(products["product_code"]))
    except SettingsError as exc:
        print(exc)
        return 1
    t = pd.read_csv(PROCESSED / "tradeoff.csv")
    if sorted(t["service_level"]) != list(settings.service_levels):
        print("The backtest is out of date for these settings. Run `python -m inventory.policy` first.")
        return 1
    wc = working_capital(t, settings.default_service_level)
    wc.drop(columns="is_baseline").to_csv(PROCESSED / "working_capital.csv", index=False)
    SUMMARY_MD.write_text(summary_markdown(wc, settings), encoding="utf-8")
    sym = SYMBOLS.get(settings.currency, "")
    for r in wc.itertuples():
        print(f"{r.service_level:>5.0%}  cash in stock {money(r.working_capital, sym):>9}  "
              f"total cost {money(r.total_cost, sym):>8}  net saving vs current {money(r.net_saving, sym):>7}")
    print(f"\nRecommended: {recommend(wc, settings.min_return_on_extra_stock):.0%}. Wrote data/processed/working_capital.csv and docs/finance-summary.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
